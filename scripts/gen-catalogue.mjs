// Writes supabase/migrations/0009_catalogue.sql from the catalogue in src/data.ts (items, cases, drop tickets, prices).
// Run:  npm run gen:catalogue   (only when src/data.ts changes; the admin catalogue editor, step C, will make this unnecessary)
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const data = await server.ssrLoadModule('/src/data.ts');
  const q = s => `'${String(s).replace(/'/g, "''")}'`;
  const items = data.ITEMS.map(i => `  (${q(i.id)}, ${q(i.weapon)}, ${q(i.skin)}, ${q(i.type)}, ${q(i.rarity)}, ${i.value})`).join(',\n');
  const cases = [...data.CASES, ...data.REWARD_CASES];
  const caseRows = cases.map(c => `  (${q(c.id)}, ${q(c.name)}, ${!!c.reward}, ${c.price})`).join(',\n');
  const entries = cases.flatMap(c => c.entries.map(e => `  (${q(c.id)}, ${q(e.item.id)}, ${e.from}, ${e.to})`)).join(',\n');
  const sql = `-- Vaultrush 0009: the catalogue the server draws from. GENERATED by scripts/gen-catalogue.mjs from src/data.ts: do not edit by hand.
-- Run in the Supabase SQL editor after 0008_wallet.sql. Safe to run again (it replaces the catalogue).
-- Prices are set so each case returns 90% on average; every item owns a range of the 100,000 tickets of its case.

delete from public.catalog_case_entries;
delete from public.catalog_cases;
delete from public.catalog_items where id not in (select item_id from public.inventory);

insert into public.catalog_items (id, weapon, skin, type, rarity, value) values
${items}
on conflict (id) do update set weapon = excluded.weapon, skin = excluded.skin, type = excluded.type, rarity = excluded.rarity, value = excluded.value;

insert into public.catalog_cases (id, name, reward, price) values
${caseRows};

insert into public.catalog_case_entries (case_id, item_id, ticket_from, ticket_to) values
${entries};
`;
  writeFileSync(new URL('../supabase/migrations/0009_catalogue.sql', import.meta.url), sql);
  console.log(`items ${data.ITEMS.length}, cases ${cases.length}, entries ${cases.reduce((n, c) => n + c.entries.length, 0)}`);
} finally { await server.close(); }
